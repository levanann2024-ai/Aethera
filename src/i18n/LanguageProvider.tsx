function translate(text: string): string {
  const directTranslation = translations[text];
  if (directTranslation) return directTranslation;

  const rowLanguage = text.match(/^Dòng (\d+): source_language phải là "tay" \(Tày\) hoặc "muong" \(Mường\)\.$/);
  if (rowLanguage) return `Row ${rowLanguage[1]}: source_language must be "tay" (Tày) or "muong" (Mường).`;
  const extraCells = text.match(/^Dòng (\d+): có nhiều ô hơn số cột tiêu đề\.$/);
  if (extraCells) return `Row ${extraCells[1]}: there are more cells than header columns.`;
  const emptyEntry = text.match(/^Dòng (\d+): từ và nghĩa không được để trống\.$/);
  if (emptyEntry) return `Row ${emptyEntry[1]}: the word and meaning are required.`;
  const invalidEntry = text.match(/^Mục từ số (\d+) không hợp lệ\.(.*)$/);
  if (invalidEntry) return `Entry ${invalidEntry[1]} is invalid.${invalidEntry[2] ? ' Check its language, word, meaning, and field lengths.' : ''}`;
  const missingColumns = text.match(/^Thiếu cột bắt buộc: (.+)\.$/);
  if (missingColumns) return `Missing required columns: ${missingColumns[1]}.`;
  return text;
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<UiLanguage>(() => (
    window.localStorage.getItem('kyflow-language') === 'en' ? 'en' : 'vi'
  ));

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = useCallback((nextLanguage: UiLanguage) => {
    window.localStorage.setItem('kyflow-language', nextLanguage);
    document.documentElement.lang = nextLanguage;
    setLanguageState(nextLanguage);
  }, []);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (text) => language === 'en' ? translate(text) : text,
  }), [language, setLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
